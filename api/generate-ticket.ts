/**
 * POST /api/generate-ticket
 *
 * Generates a PNG ticket for a registration and uploads it to the
 * `tickets` storage bucket, then saves the STORAGE PATH to
 * event_responses.ticket_url.
 *
 * Body: { registration_id: string, regenerate?: boolean }
 * Response: { ticket_url: string }   // a storage path, e.g.
 *                                     // tickets/<event_id>/<registration_id>.png
 *
 * ── AUTH ────────────────────────────────────────────────────────────────────
 * This endpoint had NO authorization at all: anyone who learned (or guessed)
 * a registration_id could render — and therefore read — anyone's ticket.
 * It now requires EITHER
 *   (a) `Authorization: Bearer <supabase access token>` belonging to a
 *       superadmin / org admin / host of the registration's event
 *       (401 unauthenticated, 403 wrong org), OR
 *   (b) the server-to-server `x-internal-secret` header
 *       (INTERNAL_API_SECRET || CRON_SECRET || SETUP_SECRET), used by
 *       on-registration.ts so the anonymous signup funnel can still render a
 *       ticket without a user session.
 * Rate limit: 20 generations / 10 min per caller (PNG rendering + storage
 * upload + DB write is the most expensive thing this API does).
 *
 * ── PRIVATE BUCKET ──────────────────────────────────────────────────────────
 * The `tickets` bucket is going PRIVATE (it used to be world-readable and
 * leaked every attendee's name and QR through a public URL), so
 * `getPublicUrl()` is dead. We store and return the storage PATH instead.
 * Rows written before the migration still contain a full public URL; those are
 * passed back untouched (backward compatible) — use /api/ticket-image to get a
 * short-lived signed URL for display.
 *
 * Server-side only. Uses the SUPABASE_SERVICE_ROLE_KEY (never exposed to
 * the browser). The QR encodes ONLY the random qr_token (unguessable).
 *
 * Dependency notes (learned the hard way on Vercel's Node runtime):
 *  - @supabase/supabase-js + qrcode-generator MUST be dynamically imported
 *    inside the handler. satori / @resvg/resvg-js / @vercel/og ALL crash the
 *    Vercel function at init (FUNCTION_INVOCATION_FAILED).
 *  - the same applies to the shared helpers in ./_lib: they MUST be imported
 *    with `await import(...)` INSIDE the handler, never statically at the top.
 *  - pureimage is a PURE-JS PNG encoder (no native binary) — the only
 *    rasterizer that loads reliably here. Email clients can't preview SVG
 *    attachments, so we ship PNG (opens everywhere).
 *  - pureimage's TTF loader is broken here, so text is drawn with a
 *    self-contained 5x7 bitmap font — zero font-file dependency.
 *  - The renderer is inlined (a separate api/_lib .ts import also crashed
 *    the Vercel function bundler).
 *
 * ── TEMPLATE MODE (events.ticket_template_path) ────────────────────────────
 * When `events.ticket_template_path` is set, the ticket is rendered on top of
 * the event's own artwork instead of the default layout:
 *   1. download `bucket(ticket-templates)`.
 *      `events.ticket_template_path` — naming contract:
 *      `{event_id}/ticket-template.png`. Upload via a service-role or staff
 *      write (bucket RLS: staff = write, service role = always read).
 *   2. draw that PNG as the base layer at its NATIVE size (W×H of the bitmap),
 *   3. stamp the dynamic data into the documented SAFE ZONES:
 *        attendee name : x = 80px, y = 74% of H, width ≤ 65% of W,
 *                        glyph block ≈54px  → bitmap-font scale 8 (56px block)
 *        unique code   : x = 80px, y = 80% of H, glyph block ≈64px
 *                        → bitmap-font scale 9 (63px block)
 *        QR            : 360×360px anchored bottom-right with 90px margins
 *                        (top-left at W-450, H-450), inside a +22px white
 *                        rounded card. The token QR is generated by the exact
 *                        same qrcode-generator call path as the default mode.
 *      Anti-collision: name/code are clamped out of the QR card's column and
 *      drawn on a semi-opaque white rounded pill in solid dark ink
 *      (#14110E), so they survive templates with imagery.
 *      Widths are capped by min(65% of W, up to the QR card's left edge-12px).
 *
 * Template robustness (never let a bad template take the funnel down):
 *   - download/decode failure, wrong mime (magic-byte sniff, PNG expected —
 *     JPEG tolerated via pureimage's decoder), non-image bytes, a template
 *     too small to host the QR, or a bitmap over 16 MP ⇒ fall back to the
 *     DEFAULT render and log a warning (HTTP 200 with a normal ticket).
 *   - template > 4 MB ⇒ 400 to the caller: the host must upload a smaller
 *     template; rendering would be pointless either way.
 *   - unset/invalid path ⇒ default render, as before.
 * NOTE: an already-issued ticket_url is returned untouched unless
 * `regenerate: true` (duplicate safety). Changing/replacing a template on the
 * event does NOT retroactively re-render existing tickets — callers must
 * regenerate (payments pipeline does this after payment confirms).
 *
 * ── DEFAULT LAYOUT (drawn when no template is set; DO NOT regress) ─────────
 * Canvas 600×300, background #14110E:
 *   (26, 26) scale 3   MAKEYOURPASS wordmark, #FF4D2E
 *   (26, 60)           event title — scale 3, falls to scale 2 when
 *                      title.length > 22; truncated at 34 chars
 *   (26,100) scale 2   date · time, ≤40 chars
 *   (26,122) scale 2   venue, ≤40 chars
 *   (26,150) scale 2   "NAME: <attendee>", ≤40 chars
 *   x=394              dashed vertical perforation (2×5px #FF4D2E every 10px,
 *                      y=16..284)
 *   (410, 22..226)     164px-wide white stub (Y range 22..226)
 *   QR                 132×132 at (424, 36) inside the stub, 14px white quiet
 *                      zone supplied by the stub itself; cells ceil()'d
 *   unique code        centered under the QR at y=196, scale 3 (scale 2 when
 *                      code.length > 10), ink #14110E
 */

