// Safe-zone constants. Scale mapping: bitmap glyph block = 7 × scale, advance
// = 6 × scale (there are no real glyph metrics on a 5×7 bitmap font).
const TEMPLATE_TEXT_X = 80 // spec: "x=80" for both name and code
const TEMPLATE_NAME_Y_FRAC = 0.74 // spec: attendee name at ~74% of height
const TEMPLATE_NAME_W_FRAC = 0.65 // spec: name zone width ~65% of template width
const TEMPLATE_CODE_Y_FRAC = 0.8 // spec: unique code at ~80% of height
const TEMPLATE_NAME_SCALE = 8 // 7×8 = 56px glyph block  ("bold ~54px")
const TEMPLATE_CODE_SCALE = 9 // 7×9 = 63px glyph block  ("bold ~64px")
const TEMPLATE_QR_SIZE = 360 // spec: 360×360 QR…
const TEMPLATE_QR_MARGIN = 90 // …with ~90px margins, anchored bottom-right
const TEMPLATE_QR_CARD_PAD = 22 // white rounded card behind the QR (+pad px)
const TEMPLATE_QR_MIN_SIZE = 120 // a QR smaller than this is not scannable
const TEMPLATE_INK = '#14110E' // solid dark ink (theme.primary) for overlay text
const TEMPLATE_PILL_FILL = 'rgba(255,255,255,0.85)' // readability on imagery
const TEMPLATE_ALIGNMENT_GAP = 12 // min gap between overlay text and QR card
const TEMPLATE_MAX_BYTES = 4 * 1024 * 1024 // >4MB template ⇒ 400 to caller
const TEMPLATE_MAX_PIXELS = 16_000_000 // decoded bitmap sanity guard (~16MP)

interface TemplateOverlayLayout {
  nameX: number
  nameY: number
  nameMaxW: number
  codeX: number
  codeY: number
  codeMaxW: number
  qrX: number
  qrY: number
  qrSize: number
}

/**
 * Overlay geometry for a template of native size W×H. Returns null when the
 * template is physically too small to host the mandatory QR zone.
 */
function templateOverlayLayout(W: number, H: number): TemplateOverlayLayout | null {
  let qrSize = TEMPLATE_QR_SIZE
  const fitQR = Math.min(W, H) - 2 * TEMPLATE_QR_MARGIN
  if (fitQR < qrSize) {
    if (fitQR < TEMPLATE_QR_MIN_SIZE) return null
    qrSize = Math.floor(fitQR)
  }
  const qrX = W - TEMPLATE_QR_MARGIN - qrSize
  const qrY = H - TEMPLATE_QR_MARGIN - qrSize
  // Anti-collision: free-form text never enters the QR card's column.
  const textCap = Math.max(0, qrX - TEMPLATE_QR_CARD_PAD - TEMPLATE_ALIGNMENT_GAP - TEMPLATE_TEXT_X)
  return {
    nameX: TEMPLATE_TEXT_X,
    nameY: Math.round(H * TEMPLATE_NAME_Y_FRAC),
    nameMaxW: Math.min(Math.round(W * TEMPLATE_NAME_W_FRAC), textCap),
    codeX: TEMPLATE_TEXT_X,
    codeY: Math.round(H * TEMPLATE_CODE_Y_FRAC),
    codeMaxW: textCap,
    qrX,
    qrY,
    qrSize,
  }
}

/** Rounded semi-opaque backdrop (pureimage has no shadow/blur; roundRect is supported). */
function drawRoundedPill(ctx: any, x: number, y: number, w: number, h: number, r: number, fill: string) {
  ctx.beginPath()
  ctx.roundRect(x, y, w, h, r)
  ctx.fillStyle = fill
  ctx.fill()
}

/** Shortens ultra-long text to fit maxWidthPx at the given scale (bitmap font). */
function truncateToWidth(text: string, scale: number, maxWidthPx: number): string {
  if (maxWidthPx <= 0) return ''
  if (textWidth(text, scale) <= maxWidthPx) return text
  const maxChars = Math.floor(maxWidthPx / (6 * scale)) - 2 // reserve '..'
  return maxChars > 0 ? text.slice(0, maxChars) + '..' : ''
}

/** One overlay text block: white rounded pill + solid dark ink text. */
function drawTemplateText(ctx: any, text: string, x: number, y: number, scale: number, maxWidth: number) {
  const pillPadX = 20
  const pillPadY = 14
  const shown = truncateToWidth(text, scale, maxWidth - 2 * pillPadX)
  if (!shown) return
  const w = Math.min(maxWidth, textWidth(shown, scale) + 2 * pillPadX)
  drawRoundedPill(ctx, x - pillPadX, y, w, 7 * scale + 2 * pillPadY, 16, TEMPLATE_PILL_FILL)
  drawText(ctx, shown, x, y + pillPadY, scale, TEMPLATE_INK)
}

/**
 * Render the ticket over an event's own template artwork at its native size.
 * Draw order: dark base ⇒ template ⇒ QR card+QR ⇒ name ⇒ code so the text is
 * never covered by the QR card.
 */
function renderTemplateTicketCanvas(
  PImage: any,
  tmpl: any, // pureimage Bitmap of the downloaded template
  layout: TemplateOverlayLayout,
  data: { name: string; code: string; count: number; modules: boolean[][] },
): any {
  const canvas = PImage.make(tmpl.width, tmpl.height)
  const ctx = canvas.getContext('2d')

  // Base layer: fill dark first so transparent template pixels don't flash
  // black, then draw the template 1:1 at its native size.
  ctx.fillStyle = TEMPLATE_INK
  ctx.fillRect(0, 0, tmpl.width, tmpl.height)
  ctx.drawImage(tmpl, 0, 0, tmpl.width, tmpl.height)

  // QR: unique_code card (white, +22px quiet zone) anchored bottom-right, then
  // the SAME module-grid painter as the default renderer.
  const pad = TEMPLATE_QR_CARD_PAD
  drawRoundedPill(
    ctx,
    layout.qrX - pad,
    layout.qrY - pad,
    layout.qrSize + 2 * pad,
    layout.qrSize + 2 * pad,
    18,
    'rgba(255,255,255,0.96)',
  )
  ctx.fillStyle = '#000000'
  const cell = layout.qrSize / data.count
  for (let r = 0; r < data.count; r++)
    for (let c = 0; c < data.count; c++)
      if (data.modules[r][c])
        ctx.fillRect(layout.qrX + c * cell, layout.qrY + r * cell, Math.ceil(cell), Math.ceil(cell))

  // Safe-zone overlays (see header for the exact spec).
  drawTemplateText(ctx, data.name, layout.nameX, layout.nameY, TEMPLATE_NAME_SCALE, layout.nameMaxW)
  drawTemplateText(ctx, data.code, layout.codeX, layout.codeY, TEMPLATE_CODE_SCALE, layout.codeMaxW)

  return canvas
}

/**
 * Download + decode the event's template PNG (service role: the
 * `ticket-templates` bucket is private, staff-write / service-read).
 * Contract: path `{event_id}/ticket-template.png`, PNG ≤4MB. A mislabeled
 * JPEG is still decoded through pureimage's own public decoder (jpeg-js
 * stays internal to pureimage — no transitive dependency is imported
 * directly). Any failure ⇒ `failed`, callers fall back to the default render.
 */
type TemplateLoad = { kind: 'ok'; bmp: any } | { kind: 'oversize' } | { kind: 'failed' }

async function loadTemplateBitmap(sb: any, path: string, pure: any): Promise<TemplateLoad> {
  try {
    const { data, error } = await sb.storage.from('ticket-templates').download(path)
    if (error || !data) {
      console.warn('[generate-ticket] template download failed; using default render:', error?.message || error)
      return { kind: 'failed' }
    }
    const declared = typeof data.size === 'number' ? data.size : 0
    if (declared > TEMPLATE_MAX_BYTES) return { kind: 'oversize' }

    const buf = Buffer.from(await data.arrayBuffer())
    if (buf.length > TEMPLATE_MAX_BYTES) return { kind: 'oversize' }

    // Magic-byte sniff (runtimes lie about Blob.type; the path extension may
    // disagree with the actual bytes too).
    const isPng = buf.length > 8 && buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47
    const isJpeg = buf.length > 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff
    if (!isPng && !isJpeg) {
      console.warn('[generate-ticket] template is not a PNG/JPEG; using default render')
      return { kind: 'failed' }
    }

    const decode: ((s: any) => Promise<any>) | undefined = (pure as any)[
      isPng ? 'decodePNGFromStream' : 'decodeJPEGFromStream'
    ]
    if (typeof decode !== 'function') {
      console.warn('[generate-ticket] pureimage decoder unavailable; using default render')
      return { kind: 'failed' }
    }

    const { Readable } = await import('stream')
    const stream = new Readable()
    stream.push(buf)
    stream.push(null)
    const bmp = await decode(stream)

    if (!bmp || !(bmp.width > 0) || !(bmp.height > 0) || bmp.width * bmp.height > TEMPLATE_MAX_PIXELS) {
      console.warn('[generate-ticket] template decodes to an unusable/oversized bitmap; using default render')
      return { kind: 'failed' }
    }
    return { kind: 'ok', bmp }
  } catch (err) {
    console.warn('[generate-ticket] template load failed; using default render:', err)
    return { kind: 'failed' }
  }
}

/**
 * Sanity-validate the DB-supplied template path before handing it to storage.
 * Mirrors storagePathFromTicketUrl() in api/ticket-image.ts (no traversal).
 * Expected real-world value: `{event_id}/ticket-template.png`.
 */
function isValidTemplatePath(path: string): boolean {
  return path.length > 0 && path.length <= 256 && !path.startsWith('/') && !path.includes('..') && !path.includes('\\') && /^[A-Za-z0-9._/-]+$/.test(path)
}
/**
 * The default (no-template) renderer — pixel-for-pixel identical to the layout
 * this file shipped with before template mode existed. Geometry documented in
 * the "DEFAULT LAYOUT" header block above.
 */
function renderDefaultTicketCanvas(
  PImage: any,
  data: { title: string; dateStr: string; venue: string; name: string; code: string; count: number; modules: boolean[][] },
): any {
  const W = 600, H = 300
  const canvas = PImage.make(W, H)
  const ctx = canvas.getContext('2d')
  ctx.fillStyle = '#14110E'; ctx.fillRect(0, 0, W, H)

  drawText(ctx, 'MAKEYOURPASS', 26, 26, 3, '#FF4D2E')
  // title (wrap if very long)
  const tScale = data.title.length > 22 ? 2 : 3
  drawText(ctx, data.title.slice(0, 34), 26, 60, tScale, '#FFFFFF')
  drawText(ctx, data.dateStr.slice(0, 40), 26, 100, 2, '#FFFFFF')
  drawText(ctx, data.venue.slice(0, 40), 26, 122, 2, '#FFFFFF')
  drawText(ctx, data.name.slice(0, 40), 26, 150, 2, '#FFFFFF')

  // dashed divider (segments; pureimage has no setLineDash)
  ctx.fillStyle = '#FF4D2E'
  for (let y = 16; y < 284; y += 10) ctx.fillRect(394, y, 2, 5)

  // white stub + QR
  ctx.fillStyle = '#FFFFFF'; ctx.fillRect(410, 22, 164, 204)
  const qrSize = 132, qrPad = 14, cell = qrSize / data.count
  const ox = 410 + qrPad, oy = 22 + qrPad
  ctx.fillStyle = '#000000'
  for (let r = 0; r < data.count; r++)
    for (let c = 0; c < data.count; c++)
      if (data.modules[r][c]) ctx.fillRect(ox + c * cell, oy + r * cell, Math.ceil(cell), Math.ceil(cell))
  // code (centered under QR, inside white stub)
  const cScale = data.code.length > 10 ? 2 : 3
  const cw = textWidth(data.code, cScale)
  drawText(ctx, data.code, 410 + (164 - cw) / 2, 196, cScale, '#14110E')

  return canvas
}

export default async function handler(req: any, res: any) {
  // NOTE: every helper is dynamically imported INSIDE the handler — a static
  // top-level import of _lib/* crashes the Vercel function bundler.

  if (applyCors(req, res)) return
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' })

  try {
    const body = readBody(req)
    if (body === null) return fail(res, 400, 'Invalid request body')
    const { registration_id, regenerate } = body as { registration_id?: string; regenerate?: boolean }
    if (!isUuid(registration_id)) return res.status(400).json({ error: 'registration_id required' })

    const sb = await serviceClient()
    if (!sb) return fail(res, 500, 'Server not configured')

    // ── Auth: user token with org scoping, or the internal server secret ──
    const expectedSecret =
      process.env.INTERNAL_API_SECRET || process.env.CRON_SECRET || process.env.SETUP_SECRET || ''
    const gotSecret = String(req.headers['x-internal-secret'] || '')
    const internal =
      !!expectedSecret && gotSecret.length === expectedSecret.length && gotSecret === expectedSecret

    const caller = await resolveCaller(req)
    if (!caller && !internal) return fail(res, 401, 'Authentication required')

    const rl = await rateLimit(
      `gen-ticket:${caller ? caller.id : `internal:${clientIp(req)}`}`,
      20,
      10 * 60 * 1000,
    )
    if (applyLimitHeaders(res, rl)) {
      return res.status(429).json({ error: 'Too many requests. Please try again shortly.' })
    }

    if (caller) {
      const access = await requireResponseAccess(sb, caller, registration_id)
      if (!access.ok) {
        if (access.status === 404) return fail(res, 404, 'Registration not found')
        return fail(res, access.status, access.error)
      }
    }

    // The template column may not exist yet if the schema migration hasn't
    // landed — retry WITHOUT it (template mode degrades to default rendering,
    // but ticket generation never 500s on a rollout ordering issue).
    const WITH_TEMPLATE_SELECT =
      'id, event_id, respondent_name, respondent_email, unique_code, qr_token, ticket_url, events(title, date, time, venue, ticket_template_path)'
    const BASE_SELECT =
      'id, event_id, respondent_name, respondent_email, unique_code, qr_token, ticket_url, events(title, date, time, venue)'

    let regRes = await sb.from('event_responses').select(WITH_TEMPLATE_SELECT).eq('id', registration_id).maybeSingle()
    if (regRes?.error && /ticket_template_path/i.test(String(regRes.error?.message ?? ''))) {
      console.warn('[generate-ticket] events.ticket_template_path unavailable; rendering without template')
      regRes = await sb.from('event_responses').select(BASE_SELECT).eq('id', registration_id).maybeSingle()
    }
    const reg = regRes?.data
    const regErr = regRes?.error
    if (regErr) return fail(res, 500, 'Internal error', regErr)
    if (!reg) return res.status(404).json({ error: 'Registration not found' })

    // Legacy rows still hold a full public URL — hand it back untouched.
    if (reg.ticket_url && !regenerate) return res.status(200).json({ ticket_url: reg.ticket_url })

    // Heavy modules are imported HERE (after auth) so an unauthorized or
    // cached request never pays for loading pureimage/qrcode at all.
    const qrg = (await import('qrcode-generator')).default
    const pure = await import('pureimage')
    const PImage = ((pure as any).default || pure)
    const ev = (reg as any).events || {}

    // QR as module grid — the SAME generation call path is used in template
    // mode and default mode (encodes ONLY the random qr_token).
    const qr = qrg(0, 'M')
    qr.addData(reg.qr_token)
    qr.make()
    const count = qr.getModuleCount()
    const modules: boolean[][] = []
    for (let r = 0; r < count; r++) {
      modules[r] = []
      for (let c = 0; c < count; c++) modules[r][c] = qr.isDark(r, c)
    }

    const dateStr = [ev.date, ev.time].filter(Boolean).join(' . ')
    const title = (ev.title || 'EVENT').toString().toUpperCase()
    const name = ('NAME: ' + (reg.respondent_name || '')).toUpperCase()
    const venue = (ev.venue || '').toString().toUpperCase()
    const code = (reg.unique_code || 'PENDING').toUpperCase()

    let canvas: any
    // ── Template mode: draw the event's own artwork + safe-zone overlays ──
    const rawTemplatePath = typeof ev.ticket_template_path === 'string' ? ev.ticket_template_path.trim() : ''
    const templatePath = rawTemplatePath && isValidTemplatePath(rawTemplatePath) ? rawTemplatePath : ''
    if (rawTemplatePath && !templatePath) {
      console.warn('[generate-ticket] ignoring unsafe ticket_template_path; using default render')
    }
    if (templatePath) {
      const loaded = await loadTemplateBitmap(sb, templatePath, pure)
      if (loaded.kind === 'oversize') {
        // A template over the cap is a host-data problem, not a renderer
        // fault — surface it instead of silently producing tickets that no
        // longer reflect the artwork the org configured.
        return res
          .status(400)
          .json({ error: 'Ticket template is larger than 4 MB. Please upload a smaller template PNG (≤4MB).' })
      }
      if (loaded.kind === 'ok') {
        const layout = templateOverlayLayout(loaded.bmp.width, loaded.bmp.height)
        if (layout) {
          canvas = renderTemplateTicketCanvas(PImage, loaded.bmp, layout, {
            name: (reg.respondent_name || 'ATTENDEE').toString().toUpperCase(),
            code,
            count,
            modules,
          })
        } else {
          console.warn('[generate-ticket] template too small to host the QR zone; using default render')
        }
      }
      // loaded.kind === 'failed' → fall through to the default renderer (the
      // ticket must always ship; the broken template is logged server-side).
    }
    // ── No/failed template: default render, byte-identical to before ──
    if (!canvas) {
      canvas = renderDefaultTicketCanvas(PImage, { title, dateStr, venue, name, code, count, modules })
    }

    const chunks: Uint8Array[] = []
    const { Writable } = await import('stream')
    const sink = new Writable({ write(chunk: any, _enc: any, next: any) { chunks.push(chunk); next() } })
    await PImage.encodePNGToStream(canvas, sink as any)
    const png = Buffer.concat(chunks)

    // NOTE: .from('tickets') already scopes to the bucket — the object name
    // must NOT repeat the `tickets/` prefix (that would address
    // `tickets/tickets/…`, which every reader normalises away from).
    const filePath = `${reg.event_id}/${reg.id}.png`
    const { error: upErr } = await sb.storage
      .from('tickets')
      .upload(filePath, png, { contentType: 'image/png', upsert: true })
    if (upErr) return fail(res, 500, 'Ticket upload failed', upErr)

    // The bucket is PRIVATE: store the storage PATH, not a public URL.
    // getPublicUrl() is intentionally gone — it would hand out a dead link
    // the moment the bucket migration lands, and a working one while the
    // bucket is still public (the attendee-name leak we are closing).
    const { error: dbErr } = await sb
      .from('event_responses')
      .update({ ticket_url: filePath })
      .eq('id', reg.id)
    if (dbErr) return fail(res, 500, 'Internal error', dbErr)

    return res.status(200).json({ ticket_url: filePath })
  } catch (err: unknown) {
    return fail(res, 500, 'Internal error', err)
  }
}
